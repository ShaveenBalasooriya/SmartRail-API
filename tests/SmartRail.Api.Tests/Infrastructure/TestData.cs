using System.Globalization;
using System.Net;

namespace SmartRail.Api.Tests.Infrastructure;

/// <summary>The identifiers one write route needs, all of them this test's own.</summary>
/// <param name="JourneyId">
/// The controller's journey: untouched when the setup started, with one delay published on it.
/// </param>
/// <param name="StopSequence">Its calling stop that can still depart and that has a second platform.</param>
/// <param name="PlatformId">Another platform of that stop's station, which the stop does not use.</param>
/// <param name="ChangeId">The delay this setup published on that journey, which a correction can name.</param>
/// <param name="DepartureJourneyId">The untouched journey whose departure the guard's route logs.</param>
/// <param name="DepartureStopSequence">A calling, non-final stop of that journey that can still depart.</param>
/// <param name="TerminationJourneyId">
/// A journey this setup departed once, so it is running and an early termination is a real write.
/// </param>
/// <param name="TerminationStopSequence">The calling, non-final stop after that departure where it may end.</param>
internal sealed record ApiIds(
    Guid JourneyId,
    int StopSequence,
    Guid PlatformId,
    Guid ChangeId,
    Guid DepartureJourneyId,
    int DepartureStopSequence,
    Guid TerminationJourneyId,
    int TerminationStopSequence);

/// <summary>A journey, a stop of it, and the platform a change would move the stop to.</summary>
/// <param name="Journey">The journey.</param>
/// <param name="Stop">The stop whose platform changes.</param>
/// <param name="PlatformId">Another platform of the stop's station.</param>
/// <param name="ForeignPlatformId">A platform of a different station, which the stop may not move to.</param>
internal sealed record PlatformMove(GuardJourney Journey, GuardStop Stop, Guid PlatformId, Guid ForeignPlatformId);

/// <summary>
/// The test data: every journey, stop and platform is looked up through the API, and every id a
/// test asserts on is one the API returned to it (test-suite-review §4 "Test data").
/// </summary>
internal static class TestData
{
    /// <summary>How long the day's journeys may take to appear: they are generated after start-up.</summary>
    private static readonly TimeSpan GenerationTimeout = TimeSpan.FromSeconds(30);

    /// <summary>How often the generator's progress is checked while it is still running.</summary>
    private static readonly TimeSpan PollInterval = TimeSpan.FromMilliseconds(200);

    /// <summary>The calling guard's journeys today, from the guard's own view.</summary>
    /// <remarks>
    /// The journeys are generated by a hosted service after the Host starts, so the first read of a
    /// fresh database polls until they exist rather than assuming they already do.
    /// </remarks>
    public static async Task<IReadOnlyList<GuardJourney>> GuardJourneysAsync(this ApiTarget api)
    {
        var deadline = DateTimeOffset.UtcNow + GenerationTimeout;

        while (true)
        {
            using var response = await api.GetAsync(Urls.GuardJourneys, api.Guard);
            await response.HasStatusAsync(HttpStatusCode.OK);

            var journeys = await response.ReadAsync<List<GuardJourney>>();
            if (journeys.Count > 0)
            {
                return journeys;
            }

            Assert.True(
                DateTimeOffset.UtcNow < deadline,
                $"The API listed no journey for the guard within {GenerationTimeout.TotalSeconds} s of starting.");

            await Task.Delay(PollInterval);
        }
    }

    /// <summary>A journey with at least two calling stops that nothing has changed or departed yet.</summary>
    public static async Task<GuardJourney> UntouchedJourneyAsync(this ApiTarget api) =>
        UntouchedJourney(await api.GuardJourneysAsync());

    /// <summary>A journey as the Network Controller's view shows it: status, stops and changes.</summary>
    public static async Task<JourneyDetail> DetailAsync(this ApiTarget api, Guid journeyId)
    {
        using var response = await api.GetAsync(
            Urls.ControllerJourney(journeyId),
            api.Controller);

        await response.HasStatusAsync(HttpStatusCode.OK);
        return await response.ReadAsync<JourneyDetail>();
    }

    /// <summary>One journey as the calling guard sees it, with its stops and the changes on it.</summary>
    public static async Task<GuardJourneyDetail> GuardDetailAsync(this ApiTarget api, Guid journeyId)
    {
        using var response = await api.GetAsync(
            Urls.GuardJourney(journeyId),
            api.Guard);

        await response.HasStatusAsync(HttpStatusCode.OK);
        return await response.ReadAsync<GuardJourneyDetail>();
    }

    /// <summary>The public station catalogue, which names each station's platforms.</summary>
    public static async Task<IReadOnlyList<Station>> StationsAsync(this ApiTarget api)
    {
        using var response = await api.GetAsync(Urls.Stations, Credential.None);
        await response.HasStatusAsync(HttpStatusCode.OK);

        return await response.ReadAsync<List<Station>>();
    }

    /// <summary>Publishes a delay as the Network Controller and returns the change the API answered with.</summary>
    public static async Task<JourneyChange> PublishDelayAsync(
        this ApiTarget api,
        Guid journeyId,
        int fromStopSequence,
        int minutes = 10)
    {
        using var response = await api.PostAsync(
            Urls.Delays(journeyId),
            api.Controller,
            new { fromStopSequence, minutes });

        await response.HasStatusAsync(HttpStatusCode.Created);
        return await response.ReadAsync<JourneyChange>();
    }

    /// <summary>
    /// The body of one departure log, with the client-generated identifier and device time the
    /// offline queue would produce. The same object posted twice is an identical resend.
    /// </summary>
    public static object DepartureBody(Guid journeyId, int stopSequence, Guid? id = null) => new
    {
        id = id ?? Guid.CreateVersion7(),
        journeyId,
        stopSequence,
        departedAt = DateTimeOffset.UtcNow.ToString("O", CultureInfo.InvariantCulture),
        delayCause = (string?)null,
    };

    /// <summary>A journey, one of its stops, and the platform a change would move it to.</summary>
    public static async Task<PlatformMove> PlatformMoveAsync(this ApiTarget api)
    {
        var stations = await api.StationsAsync();

        foreach (var journey in await api.GuardJourneysAsync())
        {
            foreach (var stop in journey.Stops)
            {
                if (stop.Station is null || stop.Platform is null)
                {
                    continue;
                }

                var station = stations.FirstOrDefault(candidate => candidate.Id == stop.Station.Id);
                var other = station?.Platforms.FirstOrDefault(platform => platform.Id != stop.Platform.Id);
                if (station is null || other is null)
                {
                    continue;
                }

                var foreign = stations
                    .SelectMany(candidate => candidate.Platforms)
                    .First(platform => platform.StationId != station.Id);

                return new PlatformMove(journey, stop, other.Id, foreign.Id);
            }
        }

        Assert.Fail("The seeded network has no journey stop whose station offers a second platform.");
        return null!;
    }

    /// <summary>The identifiers one write route needs, created through the API.</summary>
    /// <remarks>
    /// <para>
    /// Every identifier is prepared so the route's request is a write that would succeed with the
    /// right credential, because a "writes nothing" proof only means something when the same request
    /// with that credential would write (<c>WriteRouteAccessTests</c> makes that its positive
    /// control). Three routes need more than an untouched journey:
    /// </para>
    /// <list type="bullet">
    /// <item>
    /// The platform change moves the stop to <em>another</em> platform of its station; the stop's
    /// current platform would be refused as unchanged (409).
    /// </item>
    /// <item>
    /// The termination names a stop after a departure the setup has already logged; an untouched
    /// journey would be refused as not started (409).
    /// </item>
    /// <item>
    /// The provider's webhook is registered before the routes run, so the registration is a
    /// replacement the snapshot can see and the deactivation has a subscription to remove (204).
    /// </item>
    /// </list>
    /// </remarks>
    public static async Task<ApiIds> IdsAsync(this ApiTarget api)
    {
        var stations = await api.StationsAsync();
        var journeys = await api.JourneysForSetupAsync(stations);

        var (controller, stop, platformId) = ChangeableJourney(stations, journeys);
        var departureJourney = UntouchedJourney(journeys, controller.Id);
        var terminationJourney = UntouchedJourney(journeys, controller.Id, departureJourney.Id);

        var departureStop = departureJourney.Stops.First(candidate => !candidate.IsFinalStop);
        var departedStop = terminationJourney.Stops.First(candidate => !candidate.IsFinalStop);
        var terminationStop = StopAfter(terminationJourney, departedStop.Sequence);

        var change = await api.PublishDelayAsync(controller.Id, stop.Sequence);
        await api.RegisterWebhookAsync();

        // The termination is only a real write on a journey that has already started.
        using (var departure = await api.PostAsync(
            Urls.DepartureLogs,
            api.Guard,
            DepartureBody(terminationJourney.Id, departedStop.Sequence)))
        {
            await departure.HasStatusAsync(HttpStatusCode.Created);
        }

        return new ApiIds(
            controller.Id,
            stop.Sequence,
            platformId,
            change.Id,
            departureJourney.Id,
            departureStop.Sequence,
            terminationJourney.Id,
            terminationStop.Sequence);
    }

    /// <summary>
    /// The callback this setup registers before the provider routes run. It is not the registration
    /// route's own URL, so a replacement changes the snapshot; and the subscription is left active,
    /// so a deactivation has something to remove.
    /// </summary>
    private const string SetupCallbackUrl = "https://rail-bites.example/hooks/setup";

    /// <summary>Registers the provider's callback, so both provider write routes have a real write to make.</summary>
    private static async Task RegisterWebhookAsync(this ApiTarget api)
    {
        using var response = await api.PutAsync(
            Urls.ProviderWebhook,
            api.Provider,
            new { url = SetupCallbackUrl });

        // The first registration answers 201; a second setup call in the same database replaces it
        // and answers 200. Either way the subscription exists and is active.
        Assert.True(
            response.StatusCode is HttpStatusCode.Created or HttpStatusCode.OK,
            "The setup could not register the provider's webhook: the API answered "
            + $"{(int)response.StatusCode} ({response.StatusCode}). "
            + $"Body: {await response.Content.ReadAsStringAsync()}");
    }

    /// <summary>
    /// The guard's journeys, once the day's generation has produced the three untouched ones this
    /// setup needs and one with a stop the platform change can move. A journey reaches the guard's
    /// list only when its live state exists, and those appear one at a time after start-up, so a
    /// non-empty list is not yet the day's timetable.
    /// </summary>
    private static async Task<IReadOnlyList<GuardJourney>> JourneysForSetupAsync(
        this ApiTarget api,
        IReadOnlyList<Station> stations)
    {
        var deadline = DateTimeOffset.UtcNow + GenerationTimeout;
        var polled = 0;

        while (true)
        {
            polled++;
            var journeys = await api.GuardJourneysAsync();
            var untouched = journeys.Where(IsUntouched).ToArray();

            var changeable = untouched.Any(journey => journey.Stops.Any(stop =>
                !stop.IsFinalStop && OtherPlatformId(stations, stop) is not null));

            if (untouched.Length >= 3 && changeable)
            {
                return journeys;
            }

            // The earliest journeys generated are the small hours' inbound services, whose
            // interchange stop is their terminus; the platform change needs an outbound one, so the
            // list has to be read again rather than taken as it first appears.
            Assert.True(
                DateTimeOffset.UtcNow < deadline,
                $"After {polled} attempt(s) in {GenerationTimeout.TotalSeconds} s the guard's list "
                + $"has {untouched.Length} untouched journey(s) and "
                + $"{(changeable ? "a" : "no")} stop the platform change can move; the seeded "
                + "timetable always offers three untouched journeys and the interchange's platform.");

            await Task.Delay(PollInterval);
        }
    }

    /// <summary>True when the guard has logged no departure anywhere on the journey.</summary>
    private static bool IsUntouched(GuardJourney journey) =>
        journey.Stops.All(stop => !stop.DepartureLogged);

    /// <summary>
    /// An untouched journey other than the ones already taken, so no route's setup writes over
    /// another route's precondition.
    /// </summary>
    private static GuardJourney UntouchedJourney(IReadOnlyList<GuardJourney> journeys, params Guid[] taken)
    {
        var journey = journeys.FirstOrDefault(candidate =>
            candidate.Stops.Count >= 2
            && IsUntouched(candidate)
            && !taken.Contains(candidate.Id));

        Assert.True(
            journey is not null,
            "The guard's list has no journey with two calling stops that has not departed and is not "
            + "already used by this setup; the seeded timetable always has several.");

        return journey!;
    }

    /// <summary>
    /// An untouched journey with a calling, non-final stop whose station offers a second platform,
    /// that stop and the platform to move it to: the only place a platform change is a real write,
    /// because only the seeded interchange has more than one platform.
    /// </summary>
    private static (GuardJourney Journey, GuardStop Stop, Guid PlatformId) ChangeableJourney(
        IReadOnlyList<Station> stations,
        IReadOnlyList<GuardJourney> journeys)
    {
        foreach (var journey in journeys.Where(IsUntouched))
        {
            foreach (var stop in journey.Stops.Where(candidate => !candidate.IsFinalStop))
            {
                if (OtherPlatformId(stations, stop) is { } platformId)
                {
                    return (journey, stop, platformId);
                }
            }
        }

        Assert.Fail(
            "The seeded network has no journey stop at a station with a second platform, so the "
            + "platform change has no valid write to make; the seeded interchange always has one.");

        return default;
    }

    /// <summary>The id of a platform of the stop's station other than the one the stop uses, if any.</summary>
    private static Guid? OtherPlatformId(IReadOnlyList<Station> stations, GuardStop stop)
    {
        if (stop.Station is null || stop.Platform is null)
        {
            return null;
        }

        return stations
            .FirstOrDefault(station => station.Id == stop.Station.Id)?
            .Platforms.FirstOrDefault(platform => platform.Id != stop.Platform.Id)?.Id;
    }

    /// <summary>The journey's first calling stop after <paramref name="sequence"/> that is not its final one.</summary>
    private static GuardStop StopAfter(GuardJourney journey, int sequence)
    {
        var stop = journey.Stops.FirstOrDefault(candidate =>
            !candidate.IsFinalStop && candidate.Sequence > sequence);

        Assert.True(
            stop is not null,
            $"The journey {journey.Id} has no calling, non-final stop after sequence {sequence}; "
            + "the seeded timetable always has one.");

        return stop!;
    }
}
